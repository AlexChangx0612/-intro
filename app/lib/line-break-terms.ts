// 產生名詞清單（去除重複與單字）
export function lineBreakTerms() {
  const categories = getCatalog().categories.flatMap((c) => [...c.name.split("・"), ...(c.groups?.map((g) => g.name) ?? [])]);
  return [...new Set([...extra, ...categories].map((t) => t.trim()).filter((t) => t.length > 1))];
}
